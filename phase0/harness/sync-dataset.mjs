#!/usr/bin/env node
/**
 * Copies the canonical dataset into the Forge app as plain ES modules.
 *
 * The Forge bundler is happiest with JS modules, not JSON imports, so the
 * canonical files in phase0/dataset/ are projected into phase0/validator-probe/
 * src/data/ here. Re-run after editing the dataset; the harness checks that the
 * copy is in step.
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, '..');
const OUT = join(ROOT, 'validator-probe/src/data');

const pairs = [
  ['dataset/comments.json', 'comments.js', 'comments'],
  ['dataset/ground-truth.json', 'ground-truth.js', 'groundTruth'],
];

mkdirSync(OUT, { recursive: true });
const manifest = {};

for (const [src, dest, name] of pairs) {
  const raw = readFileSync(join(ROOT, src), 'utf8');
  const hash = createHash('sha256').update(raw).digest('hex').slice(0, 16);
  const body = `// AUTOGENERATED from phase0/${src} — do not edit. Run: node phase0/harness/sync-dataset.mjs\nexport const sha256_16 = '${hash}';\nexport const ${name} = ${raw.trim()};\nexport default ${name};\n`;
  writeFileSync(join(OUT, dest), body);
  manifest[dest] = hash;
  console.log(`wrote ${dest} (${hash})`);
}

writeFileSync(join(OUT, 'MANIFEST.json'), JSON.stringify(manifest, null, 2));
